/* ------------------------------------------------------------------ *
 * 四、语料来源可信度分级
 * ------------------------------------------------------------------ */

/**
 * `data/readings.json` 的 positionSource 分级。
 *
 * 界面必须区分展示这两类，不得把推定值呈现为考纲事实。
 */
export const SOURCE_OFFICIAL = '2026 省通知';
export const SOURCE_INFERRED = '教材对标建议';
export interface SourceInfo {
  official: boolean;
  label: string;
  /** 给用户看的说明 */
  note: string;
}

export function describeSource(positionSource: string): SourceInfo {
  if (positionSource === SOURCE_OFFICIAL) {
    return {
      official: true,
      label: '官方公布材料位置',
      note: '此篇材料位置来自江苏省 2026 年中考英语听力口语自动化考试要求公布的新增名单。',
    };
  }
  return {
    official: false,
    label: '教材对标建议（非考纲事实）',
    note: '此篇材料位置由本项目依据译林版教材单元表推定，仅供练习，不代表考纲要求。',
  };
}
